#!/usr/bin/env bun
// Derives the Claude and Codex install manifests from the tracked source tree
// and appends a version record to src/lib/generated/current-manifests.ts when
// a set changed. Existing records are written back unchanged, so a shipped
// version never moves. `bun run manifests:check` fails when this would write.
// `--base <ref>` also fails unless the records extend that ref's records
// unchanged, so a merge can never reuse a shipped version for another list.
//
// Membership comes from the git index only (`git ls-files`): `git add` a new
// file and `git rm` a deleted one before running this, so ignored, scratch or
// half-deleted files never change an install.

import { existsSync } from "node:fs";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import type {
  ClaudeManifestRecord,
  ManifestDelta,
  RuntimeManifestRecord,
} from "../lib/install-source-inventory.ts";
import { LIGHT_SKILLS } from "../lib/light-profile.ts";

const ROOT = resolve(import.meta.dir, "../..");
const OUTPUT = "src/lib/generated/current-manifests.ts";
// Interpolated so the runtime import scanner does not read the template below as this file's import.
const GENERATED_TYPES_IMPORT = "../install-source-inventory.ts";

// Repo-only tooling: the eval runners run from a checkout, never an install. Anything a
// package.json script names ships, because the installed package.json carries the script.
const DEV_ONLY = (path: string) => /^src\/(lib|scripts)\/eval-[^/]+\.ts$/.test(path);

// Files the Claude installer writes itself (baseline: full only) or copies under another name.
const CLAUDE_INSTALLER_WRITTEN = [".cc-settings-hooks-fingerprint", ".cc-settings-src-manifest"];
const CLAUDE_FULL_INSTALLER_WRITTEN = [".cc-settings-baseline.json"];
const CLAUDE_RENAMED_SOURCES = ["src/bun.lock", "src/package.json", "src/tsconfig.json"];
const CLAUDE_FULL_RENAMED_SOURCES = ["CLAUDE.md"];
const CLAUDE_FULL_ROOT_FILES = ["AGENTS.md"];
const CLAUDE_FULL_TREES = [
  "agents/",
  "docs/",
  "hooks/",
  "output-styles/",
  "profiles/",
  "rules/",
  "skills/",
  "src/",
];
// docs/rules.md indexes the rules for readers of this repo; installs load the rules themselves.
const CLAUDE_EXCLUDED = ["docs/rules.md"];

const CODEX_ROOT_FILES = [
  ".claude-plugin/marketplace.json",
  ".mcp.json",
  "bun.lock",
  "mcp.json",
  "package.json",
  "plugin.json",
  "tsconfig.json",
];
const CODEX_TREES = ["hooks/", "skills/", "src/"];
// The /audit Platform checks read this profile and these rules; Codex ships no other profiles or rules.
const CODEX_EXTRAS = [
  "profiles/native-apps.md",
  "rules/android-design.md",
  "rules/apple-design.md",
  "rules/windows-design.md",
];
// Hooks and scripts only Claude Code runs (dispatcher handlers, Claude-only hooks such as the
// git-cow worktree hook, the browser sign-in helper, the /audit grader); Codex never calls them.
const CLAUDE_ONLY_SOURCES = [
  "src/hooks/ask-gate.ts",
  "src/hooks/browser-guard.ts",
  "src/hooks/cache-cold.ts",
  "src/hooks/config-guard.ts",
  "src/hooks/dispatch.ts",
  "src/hooks/linear-gate.ts",
  "src/hooks/session-worktrees.ts",
  "src/hooks/spawn-cap.ts",
  "src/hooks/test-protect.ts",
  "src/hooks/visual-proof.ts",
  "src/hooks/worktree-cow.ts",
  "src/lib/cache-cold.ts",
  "src/scripts/browser-signin.ts",
  "src/scripts/grade-findings.ts",
];

function render(
  claude: readonly ClaudeManifestRecord[],
  codex: readonly RuntimeManifestRecord[],
): string {
  return `// Generated by \`bun run manifests:emit\` (src/scripts/emit-manifests.ts). Do not edit:
// each record is an install manifest version after the hand-written history, and a
// shipped version must never change.
import type {
  ClaudeManifestRecord,
  RuntimeManifestRecord,
} from "${GENERATED_TYPES_IMPORT}";

export const CLAUDE_MANIFEST_RECORDS: readonly ClaudeManifestRecord[] = ${JSON.stringify(claude)};

export const CODEX_RUNTIME_MANIFEST_RECORDS: readonly RuntimeManifestRecord[] = ${JSON.stringify(codex)};
`;
}

export interface ManifestRecords {
  claude: readonly ClaudeManifestRecord[];
  codex: readonly RuntimeManifestRecord[];
}

/** Why `candidate` does not extend `base` unchanged; empty when every base record is kept as is. */
export function baseRecordProblems(base: ManifestRecords, candidate: ManifestRecords): string[] {
  const problems: string[] = [];
  const compare = (kind: string, before: readonly object[], after: readonly object[]) => {
    if (after.length < before.length) {
      problems.push(`${kind} has ${after.length} records; the base has ${before.length}`);
    }
    before.forEach((record, index) => {
      if (index < after.length && !Bun.deepEquals(record, after[index])) {
        problems.push(`${kind} record ${index} differs from the base`);
      }
    });
  };
  compare("Claude", base.claude, candidate.claude);
  compare("Codex runtime", base.codex, candidate.codex);
  return problems;
}

const LAST_HAND_WRITTEN = /^const LAST_HAND_WRITTEN_VERSION = (\d+);$/m;
const HAND_WRITTEN_MODULES = [
  "src/lib/claude-managed-file-manifests.ts",
  "src/lib/codex-runtime-manifests.ts",
];

async function gitShow(ref: string, path: string): Promise<string | null> {
  const result = await Bun.$`git -C ${ROOT} show ${`${ref}:${path}`}`.quiet().nothrow();
  return result.exitCode === 0 ? result.stdout.toString() : null;
}

function lastHandWrittenVersion(source: string, label: string): number {
  const match = source.match(LAST_HAND_WRITTEN);
  if (!match) throw new Error(`No LAST_HAND_WRITTEN_VERSION constant in ${label}`);
  return Number(match[1]);
}

async function assertExtendsBase(ref: string, candidate: ManifestRecords): Promise<void> {
  const verified = await Bun.$`git -C ${ROOT} rev-parse --verify --quiet ${`${ref}^{commit}`}`
    .quiet()
    .nothrow();
  if (verified.exitCode !== 0) throw new Error(`--base ${ref} is not a commit`);
  const baseOutput = await gitShow(ref, OUTPUT);
  if (baseOutput === null) {
    console.log(`Base ${ref} has no ${OUTPUT}; nothing to extend.`);
    return;
  }
  const dir = await mkdtemp(join(tmpdir(), "cc-manifests-base-"));
  let base: ManifestRecords;
  try {
    const file = join(dir, "current-manifests.ts");
    await writeFile(file, baseOutput);
    const loaded = await import(file);
    base = { claude: loaded.CLAUDE_MANIFEST_RECORDS, codex: loaded.CODEX_RUNTIME_MANIFEST_RECORDS };
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
  const problems = baseRecordProblems(base, candidate);
  for (const path of HAND_WRITTEN_MODULES) {
    const before = await gitShow(ref, path);
    if (before === null) throw new Error(`Base ${ref} has ${OUTPUT} but no ${path}`);
    const baseVersion = lastHandWrittenVersion(before, `${ref}:${path}`);
    const ownVersion = lastHandWrittenVersion(await Bun.file(join(ROOT, path)).text(), path);
    if (baseVersion !== ownVersion) {
      problems.push(
        `${path} ends its hand-written history at ${ownVersion}; the base at ${baseVersion}`,
      );
    }
  }
  if (problems.length > 0) {
    throw new Error(
      `Install manifest records do not extend ${ref} unchanged: ${problems.join("; ")}. ` +
        `Shipped versions never change: take ${ref}'s records and run \`bun run manifests:emit\` again.`,
    );
  }
  console.log(`Records extend ${ref} unchanged.`);
}

function baseRef(args: readonly string[]): string | null {
  const index = args.indexOf("--base");
  if (index === -1) return null;
  const ref = args[index + 1];
  if (!ref || ref.startsWith("--")) throw new Error("--base needs a git ref");
  return ref;
}

async function indexedFiles(): Promise<string[]> {
  const listed = (await Bun.$`git -C ${ROOT} ls-files -z`.text()).split("\0").filter(Boolean);
  return [...new Set([...listed, OUTPUT])].sort();
}

const under = (trees: readonly string[]) => (path: string) =>
  trees.some((tree) => path.startsWith(tree));

function delta(previous: readonly string[], next: ReadonlySet<string>): ManifestDelta {
  const before = new Set(previous);
  return {
    added: [...next].filter((path) => !before.has(path)).sort(),
    removed: [...before].filter((path) => !next.has(path)).sort(),
  };
}

const changed = (d: ManifestDelta) => d.added.length > 0 || d.removed.length > 0;
const summary = (d: ManifestDelta) =>
  [...d.added.map((path) => `+ ${path}`), ...d.removed.map((path) => `- ${path}`)].join("\n  ");

async function main(): Promise<void> {
  const base = baseRef(Bun.argv.slice(2));
  const output = join(ROOT, OUTPUT);
  // Shipped records are append-only, so a missing file is an error, never a fresh start.
  if (!existsSync(output)) {
    throw new Error(`${OUTPUT} is missing. Restore it from git; never regenerate shipped records.`);
  }

  const claude = await import("../lib/claude-managed-file-manifests.ts");
  const codex = await import("../lib/codex-runtime-manifests.ts");
  const generated = await import("../lib/generated/current-manifests.ts");
  const { missingLocalImports } = await import("../lib/codex-runtime.ts");

  const tracked = (await indexedFiles()).filter((path) => !DEV_ONLY(path));
  const lightSkillTrees = LIGHT_SKILLS.map((skill) => `skills/${skill}/`);
  const srcFiles = tracked.filter(under(["src/"]));

  const claudeExcluded = new Set(CLAUDE_EXCLUDED);
  const full = new Set([
    ...CLAUDE_INSTALLER_WRITTEN,
    ...CLAUDE_FULL_INSTALLER_WRITTEN,
    ...CLAUDE_RENAMED_SOURCES,
    ...CLAUDE_FULL_RENAMED_SOURCES,
    ...tracked.filter(
      (path) =>
        (CLAUDE_FULL_ROOT_FILES.includes(path) || under(CLAUDE_FULL_TREES)(path)) &&
        !claudeExcluded.has(path),
    ),
  ]);
  const light = new Set([
    ...CLAUDE_INSTALLER_WRITTEN,
    ...CLAUDE_RENAMED_SOURCES,
    ...srcFiles,
    ...tracked.filter(under(lightSkillTrees)),
  ]);

  const claudeOnly = new Set(CLAUDE_ONLY_SOURCES);
  const codexSet = new Set(
    tracked.filter(
      (path) =>
        CODEX_ROOT_FILES.includes(path) ||
        CODEX_EXTRAS.includes(path) ||
        (under(CODEX_TREES)(path) && !claudeOnly.has(path)),
    ),
  );
  const indexed = new Set(tracked);
  const absent = [...new Set([...full, ...light, ...codexSet])]
    .filter((path) => indexed.has(path) && !existsSync(join(ROOT, path)))
    .sort();
  if (absent.length > 0) {
    throw new Error(
      `Files in the git index are missing from the working tree: ${absent.join(", ")}. ` +
        "Restore them, or `git rm` them to drop them from the install.",
    );
  }
  const missing = await missingLocalImports(ROOT, [...codexSet]);
  if (missing.length > 0) {
    throw new Error(
      `The Codex runtime would omit files its sources import: ${missing.join(", ")}. ` +
        "Remove them from CLAUDE_ONLY_SOURCES in src/scripts/emit-manifests.ts.",
    );
  }

  const claudeRecords: ClaudeManifestRecord[] = [...generated.CLAUDE_MANIFEST_RECORDS];
  const claudeVersion = claude.CURRENT_CLAUDE_MANAGED_FILES_MANIFEST_VERSION;
  const fullDelta = delta(claude.claudeManagedManifestPaths(claudeVersion, "full", OUTPUT), full);
  const lightDelta = delta(
    claude.claudeManagedManifestPaths(claudeVersion, "light", OUTPUT),
    light,
  );
  if (changed(fullDelta) || changed(lightDelta)) {
    claudeRecords.push({ version: claudeVersion + 1, full: fullDelta, light: lightDelta });
    console.log(`Claude manifest ${claudeVersion + 1}:`);
    console.log(`  full\n  ${summary(fullDelta) || "(unchanged)"}`);
    console.log(`  light\n  ${summary(lightDelta) || "(unchanged)"}`);
  } else {
    console.log(`Claude manifest unchanged at ${claudeVersion}.`);
  }

  const codexRecords: RuntimeManifestRecord[] = [...generated.CODEX_RUNTIME_MANIFEST_RECORDS];
  const codexVersion = codex.CURRENT_RUNTIME_MANIFEST_VERSION;
  const codexDelta = delta(codex.RUNTIME_SOURCE_FILES, codexSet);
  if (changed(codexDelta)) {
    codexRecords.push({ version: codexVersion + 1, ...codexDelta });
    console.log(`Codex runtime manifest ${codexVersion + 1}:\n  ${summary(codexDelta)}`);
  } else {
    console.log(`Codex runtime manifest unchanged at ${codexVersion}.`);
  }

  await writeFile(output, render(claudeRecords, codexRecords));
  const format = Bun.spawnSync(["bun", "x", "biome", "format", "--write", output], { cwd: ROOT });
  if (format.exitCode !== 0) {
    throw new Error(`biome format failed on ${OUTPUT}: ${format.stderr.toString()}`);
  }
  if (base) await assertExtendsBase(base, { claude: claudeRecords, codex: codexRecords });
}

if (import.meta.main) await main();
